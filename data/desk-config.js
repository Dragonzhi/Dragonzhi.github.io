/* ============================================================
   台面「长宽范围」配置 —— 只改这一个文件即可
   改动后无需动 CSS/JS。页面刷新即生效（本地用 python -m http.server 8000 验证）。

   下面每一项都是「边界范围」：
   - 想去掉当前自动撑大的部分、改为固定范围，就填固定数值。
   - 想维持「按内容自动撑大」，保持默认 0 / 缺省即可（见每项注释）。
   ============================================================ */

window.DESK_CONFIG = {

    /* 台面最小高度(px)：纵向地板。
       档案架(projects/shelf)卡片更多时会自动超过它(自动撑高)。
       默认 1180 与旧设计一致。想更高就调大。 */
    minHeight: 1280,

    /* 撑高时在「最高卡片底部」再留的余量(px)。
       默认 60。想卡片更贴底、页脚更靠下就调大。 */
    padBottom: 80,

    /* 台面目标宽度(px)：横向范围。
       0 = 自动随 .wrap 版心宽(约 1031px)，卡片最多只能挪到 wrap 内。
       >0 = 以此值为准，可突破 .wrap 版心，让贴贴能摆到更靠右。
       注意：设得超过屏幕视口宽时会被 body 的 overflow-x 裁掉，
       建议不超过当前屏幕宽(如 1200 / 1280)。默认 0 最稳妥。 */
    minWidth: 1280,

    /* 撑宽时在「最右卡片右沿」再留的余量(px)。
       默认 24。想卡片更靠右沿、贴纸探出版心就调大。 */
    padRight: 24,

    /* 卡片到桌沿的边界留白(px)：上下左右共用。
       默认 24 与旧设计一致。想台面更大、卡片更贴边就调小。 */
    padding: 24
};
